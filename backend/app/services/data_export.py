"""Excel export of the optimization results a planner acts on."""
import io
from typing import Any, List, Sequence, Tuple

from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.worksheet import Worksheet
from sqlalchemy.orm import Session

from app.models.base import utcnow
from app.models.inventory import Location, Product
from app.repositories.pipeline import AlertRepository, OptimizationResultRepository
from app.services.dashboard import build_dashboard_summary
from app.services.inventory import list_positions
from app.services.transportation import build_transportation_plan

HEADER_FILL = PatternFill("solid", fgColor="4F46E5")
STATUS_LABEL = {"STOCKOUT_RISK": "Stockout risk", "REORDER": "Reorder", "EXCESS": "Excess",
                "HEALTHY": "Healthy", "NO_PLAN": "No plan"}


def _sheet(wb: Workbook, title: str, headers: Sequence[str],
           rows: Sequence[Sequence[Any]]) -> Worksheet:
    ws = wb.create_sheet(title)
    ws.append(list(headers))
    for cell in ws[1]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = HEADER_FILL
    for row in rows:
        ws.append(list(row))
    for i, h in enumerate(headers, start=1):
        ws.column_dimensions[get_column_letter(i)].width = max(12, min(40, len(h) + 4))
    ws.freeze_panes = "A2"
    if rows:
        ws.auto_filter.ref = ws.dimensions
    return ws


def _r(v: Any, digits: int = 2) -> Any:
    return round(v, digits) if isinstance(v, float) else v


def build_results_workbook(db: Session, generated_by: str) -> Tuple[bytes, str]:
    """Returns the workbook bytes and a suggested file name."""
    now = utcnow()
    summary = build_dashboard_summary(db)
    locations = {loc.id: loc for loc in db.query(Location)}
    products = {p.id: p for p in db.query(Product)}

    wb = Workbook()
    ws = wb.active
    ws.title = "Summary"
    last = summary["last_run"]
    lines: List[Tuple[Any, ...]] = [
        ("Unified Inventory Optimizer — results export",),
        (),
        ("Generated (UTC)", now.strftime("%Y-%m-%d %H:%M")),
        ("Generated by", generated_by),
        ("Last pipeline run", last["id"] if last else "none yet"),
        ("Last run status", last["status"] if last else "-"),
        ("Last run started (UTC)", last["started_at"].strftime("%Y-%m-%d %H:%M") if last else "-"),
        (),
        ("Inventory value (₹, at unit cost)", summary["inventory_value"]),
        ("Average target service level", _r(summary["avg_service_level"], 4)),
        ("Share of stocked pairs above safety stock", _r(summary["fill_rate"], 4)),
        ("Pairs below safety stock (at risk)", summary["at_risk_count"]),
        ("Open alerts", summary["open_alerts"]),
    ]
    for line in lines:
        ws.append(line)
    ws["A1"].font = Font(bold=True, size=14)
    ws.column_dimensions["A"].width = 42
    ws.column_dimensions["B"].width = 40

    targets = OptimizationResultRepository(db).get_all_latest()
    target_rows = []
    for t in sorted(targets, key=lambda t: (t.location_id or "", t.product_id or "")):
        loc = locations.get(t.location_id or "")
        prod = products.get(t.product_id or "")
        if loc is None or prod is None:
            continue
        target_rows.append((loc.id, loc.name, loc.type, prod.sku, prod.name,
                            _r(t.service_level, 4), _r(t.demand_mean), _r(t.demand_std),
                            t.s_in, t.s_out, t.net_replenishment_time, _r(t.safety_stock),
                            _r(t.reorder_point), _r(t.order_quantity)))
    _sheet(wb, "Targets", (
        "Location code", "Location", "Type", "SKU", "Product", "Service level",
        "Daily demand (mean)", "Daily demand (std dev)", "Inbound service time (days)",
        "Outbound service time (days)", "Net replenishment time (days)", "Safety stock",
        "Reorder point", "Order quantity (EOQ)"), target_rows)

    positions = list_positions(db, limit=1_000_000)["items"]
    _sheet(wb, "Inventory positions", (
        "Location code", "Location", "Type", "SKU", "Product", "Status", "On hand", "On order",
        "In transit", "Inventory position", "Safety stock", "Reorder point", "Order quantity",
        "Days of cover", "Recommended order", "Stock date"), [
        (p["location_id"], p["location_name"], p["location_type"], p["sku"], p["product_name"],
         STATUS_LABEL.get(p["status"], p["status"]), p["on_hand"], p["on_order"],
         p["in_transit"], p["inventory_position"], _r(p["safety_stock"]),
         _r(p["reorder_point"]), _r(p["order_quantity"]), p["days_of_cover"],
         p["recommended_order"],
         p["snapshot_date"].strftime("%Y-%m-%d") if p["snapshot_date"] else None)
        for p in positions])

    plan = build_transportation_plan(db)
    _sheet(wb, "Transport plan", (
        "From code", "From", "To code", "To", "SKU", "Product", "Units per day",
        "Lane capacity", "Lane utilisation", "Transit days", "Cost per day (₹)"), [
        (f["source_id"], f["source_name"], f["target_id"], f["target_name"], f["sku"],
         f["product_name"], _r(f["quantity"]), f["capacity"], _r(f["utilization"], 4),
         f["transit_time"], _r(f["cost"]))
        for f in plan["lane_flows"]])

    alerts = AlertRepository(db).get_unresolved()
    _sheet(wb, "Open alerts", (
        "Raised (UTC)", "Severity", "Type", "Location code", "SKU", "Message"), [
        (a.created_at.strftime("%Y-%m-%d %H:%M") if a.created_at else None, a.severity,
         a.alert_type, a.location_id,
         products[a.product_id].sku if a.product_id in products else a.product_id, a.message)
        for a in alerts])

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue(), f"inventory-results-{now:%Y%m%d-%H%M}.xlsx"
